/// Decode VLC using OpenHTJ2K-compatible tables
/// Returns: (table_value, rho, u_off, emb_k, emb_1, bits_consumed)
pub fn decode_vlc_ohtj2k(cwd: u32, context: u16) -> (u16, u8, u8, u8, u8, u8) {
    eprintln!("VLC decode_vlc_ohtj2k: cwd=0x{:08X} (binary: {:032b}) context={}", cwd, cwd, context);
    
    // Extract lower 7 bits for codeword (since VLC decoder returns LSB-first)
    let index = ((cwd as usize) & 0x7F) + (context as usize);

    let tv = if context < 128 {
        // Use table 0 for initial context
        DEC_CXT_VLC_TABLE0.get(index).copied().unwrap_or(0)
    } else {
        // Use table 1 for non-zero context
        DEC_CXT_VLC_TABLE1.get(index & 0x3FF).copied().unwrap_or(0)
    };

    // Unpack table entry:
    // Bits 0: u_off
    // Bits 1-3: cwd_len / 2 (half bits consumed)
    // Bits 4-7: rho
    // Bits 8-11: emb_1
    // Bits 12-15: emb_k
    let u_off = (tv & 1) as u8;
    let bits_consumed = (((tv >> 1) & 7) * 2) as u8;
    let rho = ((tv >> 4) & 0xF) as u8;
    let emb_1 = ((tv >> 8) & 0xF) as u8;
    let emb_k = ((tv >> 12) & 0xF) as u8;

    if std::env::var("HTJ2K_DEBUG").is_ok() {
        eprintln!("VLC decode: cwd=0x{:08X} ctx={} idx={} -> tv=0x{:04X} rho={:04b} u_off={} emb_k={:04b} emb_1={:04b} bits={}",
            cwd, context, index, tv, rho, u_off, emb_k, emb_1, bits_consumed);
    }

    (tv, rho, u_off, emb_k, emb_1, bits_consumed)
}

/// Calculate context for next quad (per OpenHTJ2K Eq. 1)
pub fn calc_next_context(tv: u16) -> u16 {
    // context = ((tv & 0xE0) << 2) | ((tv & 0x10) << 3)
    (((tv & 0xE0) as u16) << 2) | (((tv & 0x10) as u16) << 3)
}

/// Backward-reading VLC bitstream decoder (rev_buf from OpenHTJ2K).
///
/// In HTJ2K, the MEL+VLC buffer is shared:
/// - VLC reads BACKWARD from the end (MSB of each byte first)
/// - MEL reads FORWARD from the beginning
///
/// This struct handles the backward-reading VLC portion.
pub struct VlcDecoder<'a> {
    data: &'a [u8],
    pos: isize,         // Current byte position (can go negative)
    creg: u64,          // Bit accumulator (64 bits)
    bits: u32,          // Number of valid bits in creg
    length: i32,        // Remaining bytes to read
    unstuff: bool,      // Whether next byte needs unstuffing
}

impl<'a> VlcDecoder<'a> {
    pub fn new(data: &'a [u8]) -> Self {
        eprintln!("VLC DECODER: Initializing with {} bytes: {:02X?}", data.len(), data);
        
        if data.len() < 2 {
            return Self {
                data,
                pos: -1,
                creg: 0,
                bits: 0,
                length: 0,
                unstuff: false,
            };
        }

        // data is the MEL/VLC segment (bytes [pcup..lcup-1])
        // OpenHTJ2K: buf = Dcup + Lcup - 2, length = Scup - 2
        // We're passing the segment starting at pcup, so adjust accordingly
        let len = data.len() as isize;
        let mut decoder = Self {
            data,
            pos: len - 1, // Point to last byte of segment
            creg: 0,
            bits: 0,
            length: (data.len() as i32) - 1,
            unstuff: false,
        };

        // Read first byte (only upper 4 bits are valid)
        let d = decoder.data[decoder.pos as usize];
        decoder.pos -= 1;

        decoder.creg = (d >> 4) as u64;
        decoder.bits = 4 - (if (decoder.creg & 0x07) == 0x07 { 1 } else { 0 });
        decoder.unstuff = (d | 0x0F) > 0x8F;
        
        eprintln!("VLC DECODER: First byte d={:02X}, creg={:04X}, bits={}", d, decoder.creg, decoder.bits);

        // Read initial bytes to align to 4-byte boundary
        let p = (decoder.pos as usize) & 0x03;
        let num = 1 + p;
        let tnum = num.min(decoder.length as usize);

        for _ in 0..tnum {
            if decoder.pos >= 0 {
                let d64 = decoder.data[decoder.pos as usize] as u64;
                decoder.pos -= 1;

                let d_bits = 8 - (if decoder.unstuff && ((d64 & 0x7F) == 0x7F) { 1 } else { 0 });
                decoder.creg |= d64 << decoder.bits;
                decoder.bits += d_bits;
                decoder.unstuff = d64 > 0x8F;
            }
        }
        decoder.length -= tnum as i32;

        decoder.read();
        decoder
    }

    /// Read more bytes from the buffer (process 4 bytes at a time)
    fn read(&mut self) {
        if self.bits > 32 {
            return; // Prevent overflow
        }

        let mut val = 0u32;
        if self.length > 3 {
            // Read 4 bytes at once (in reverse order since we're going backward)
            // OpenHTJ2K: val = *reinterpret_cast<uint32_t *>(buf - 3);
            // This reads buf[-3], buf[-2], buf[-1], buf[0] and interprets as little-endian u32
            // So buf[-3] is LSB, buf[0] is MSB
            if self.pos >= 3 {
                let idx = (self.pos - 3) as usize;
                // Read in order: idx, idx+1, idx+2, idx+3
                // We want idx to be LSB when we shift it to MSB position
                // Actually, let's match OpenHTJ2K exactly
                val = u32::from_le_bytes([
                    self.data[idx],
                    self.data[idx + 1],
                    self.data[idx + 2],
                    self.data[idx + 3],
                ]);
                self.pos -= 4;
                self.length -= 4;
            }
        } else if self.length > 0 {
            // Read remaining bytes one at a time
            let mut i = 24;
            while self.length > 0 && self.pos >= 0 {
                let v = self.data[self.pos as usize] as u32;
                val |= v << i;
                self.pos -= 1;
                self.length -= 1;
                i -= 8;
            }
        }

        // Accumulate bits with unstuffing
        let mut tmp = val >> 24;
        let mut bits_local;

        // Process byte 0 (MSB)
        bits_local = 8 - (if self.unstuff && (((val >> 24) & 0x7F) == 0x7F) { 1 } else { 0 });
        let mut unstuff_flag = (val >> 24) > 0x8F;

        // Process byte 1
        tmp |= ((val >> 16) & 0xFF) << bits_local;
        bits_local += 8 - (if unstuff_flag && (((val >> 16) & 0x7F) == 0x7F) { 1 } else { 0 });
        unstuff_flag = ((val >> 16) & 0xFF) > 0x8F;

        // Process byte 2
        tmp |= ((val >> 8) & 0xFF) << bits_local;
        bits_local += 8 - (if unstuff_flag && (((val >> 8) & 0x7F) == 0x7F) { 1 } else { 0 });
        unstuff_flag = ((val >> 8) & 0xFF) > 0x8F;

        // Process byte 3 (LSB)
        tmp |= (val & 0xFF) << bits_local;
        bits_local += 8 - (if unstuff_flag && ((val & 0x7F) == 0x7F) { 1 } else { 0 });
        unstuff_flag = (val & 0xFF) > 0x8F;

        // Add to Creg
        self.creg |= (tmp as u64) << self.bits;
        self.bits += bits_local;
        self.unstuff = unstuff_flag;
    }

    /// Fetch lower 32 bits of Creg
    pub fn fetch(&mut self) -> u32 {
        if self.bits < 32 {
            self.read();
            if self.bits < 32 {
                self.read();
            }
        }
        self.creg as u32 // Return lower 32 bits
    }

    /// Consume `count` bits from the LSB side and return new fetched value
    pub fn advance(&mut self, count: u8) -> u32 {
        self.creg >>= count; // Shift right to consume from LSB
        self.bits = self.bits.saturating_sub(count as u32);
        self.fetch() // Return the new fetched value (like OpenHTJ2K)
    }
}

